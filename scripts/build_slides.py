"""Build the lecture slides in slides/ to HTML, PDF and PowerPoint.

The decks are Markdown files for Marp (https://marp.app). Figures are not copied into the repository: a deck
refers to a notebook output, and this script extracts the image from the committed notebook at build time, so
the slides always show the same result as the notebook.

    ![w:1100](nb:04_SOTIF_ISO21448/02_triggering_conditions_and_scenarios.ipynb#9c269d98)
    ![w:1100](nb:04_SOTIF_ISO21448/05_criticality_metrics_and_rss.ipynb#808409b6/1)

``#<cell id>`` selects the code cell, ``/<n>`` the n-th output of that cell (default: the first output that is an
image). Diagrams drawn for the slides themselves are generated by ``slides/diagrams.py`` and referenced as
``diagrams/<name>.svg``.

    python scripts/build_slides.py --check             # resolve every figure reference; no Marp needed (CI)
    python scripts/build_slides.py                     # HTML for every deck
    python scripts/build_slides.py --pdf --pptx        # also PDF and image-based PowerPoint
    python scripts/build_slides.py --deck 04_sotif     # one deck

PDF and PowerPoint need a Chromium-based browser; set CHROME_PATH if Marp does not find one.
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SLIDES = ROOT / "slides"
OUT = SLIDES / "_build"
MARP = ["npx", "-y", "@marp-team/marp-cli@4.5.1"]

NB_REF = re.compile(r"\]\(nb:([^)#\s]+)#([A-Za-z0-9_-]+)(?:/(\d+))?\)")
DIAGRAM_REF = re.compile(r"\]\(diagrams/([A-Za-z0-9_.-]+)\)")
IMAGE_TYPES = (("image/png", "png"), ("image/jpeg", "jpg"), ("image/svg+xml", "svg"))


class SlideError(Exception):
    pass


def decks(selected: list[str] | None = None) -> list[Path]:
    found = sorted(p for p in SLIDES.glob("[0-9][0-9]_*.md"))
    if selected:
        found = [p for p in found if p.stem in selected]
        missing = set(selected) - {p.stem for p in found}
        if missing:
            raise SlideError(f"unknown deck(s): {', '.join(sorted(missing))}")
    return found


def _image_output(nb_path: str, cell_id: str, index: int | None, cache: dict) -> tuple[bytes, str]:
    path = ROOT / nb_path
    if not path.exists():
        raise SlideError(f"notebook not found: {nb_path}")
    if path not in cache:
        cache[path] = {c.get("id"): c for c in json.loads(path.read_text(encoding="utf-8"))["cells"]}
    cell = cache[path].get(cell_id)
    if cell is None:
        raise SlideError(f"{nb_path}: no cell with id {cell_id}")
    outputs = cell.get("outputs", [])
    candidates = [outputs[index]] if index is not None and index < len(outputs) else outputs
    if index is not None and index >= len(outputs):
        raise SlideError(f"{nb_path}#{cell_id}: output {index} does not exist ({len(outputs)} outputs)")
    for out in candidates:
        data = out.get("data", {})
        for mime, ext in IMAGE_TYPES:
            if mime in data:
                raw = data[mime]
                if ext == "svg":
                    return ("".join(raw) if isinstance(raw, list) else raw).encode("utf-8"), ext
                return base64.b64decode("".join(raw) if isinstance(raw, list) else raw), ext
    where = f"output {index}" if index is not None else "any output"
    raise SlideError(f"{nb_path}#{cell_id}: {where} is not an image")


def resolve(deck: Path, write: bool, cache: dict) -> tuple[str, list[str]]:
    """Return the deck text with figure references replaced by build paths, and the list of problems."""
    text = deck.read_text(encoding="utf-8")
    problems: list[str] = []

    def nb_sub(m: re.Match) -> str:
        nb_path, cell_id, idx = m.group(1), m.group(2), m.group(3)
        try:
            blob, ext = _image_output(nb_path, cell_id, int(idx) if idx else None, cache)
        except SlideError as exc:
            problems.append(f"{deck.name}: {exc}")
            return m.group(0)
        name = f"{Path(nb_path).parent.name[:2]}-{Path(nb_path).stem[:2]}_{cell_id}_{idx or 0}.{ext}"
        if write:
            (OUT / "fig").mkdir(parents=True, exist_ok=True)
            (OUT / "fig" / name).write_bytes(blob)
        return f"](fig/{name})"

    def diagram_sub(m: re.Match) -> str:
        if not (OUT / "diagrams" / m.group(1)).exists() and write:
            problems.append(f"{deck.name}: diagram {m.group(1)} was not generated by slides/diagrams.py")
        return m.group(0)

    text = NB_REF.sub(nb_sub, text)
    text = DIAGRAM_REF.sub(diagram_sub, text)
    return text, problems


def diagram_names() -> set[str]:
    sys.path.insert(0, str(SLIDES))
    import diagrams  # noqa: E402  (slides/diagrams.py)
    return set(diagrams.DIAGRAMS)


def check(selected: list[str] | None) -> int:
    cache: dict = {}
    problems: list[str] = []
    known = diagram_names()
    for deck in decks(selected):
        _, p = resolve(deck, write=False, cache=cache)
        problems += p
        for name in DIAGRAM_REF.findall(deck.read_text(encoding="utf-8")):
            if Path(name).stem not in known:
                problems.append(f"{deck.name}: diagram {name} is not defined in slides/diagrams.py")
    for p in problems:
        print("ERROR", p)
    n = len(decks(selected))
    print(f"{n} deck(s) checked: {'OK' if not problems else f'{len(problems)} problem(s)'}")
    return 1 if problems else 0


def build(selected: list[str] | None, pdf: bool, pptx: bool) -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(SLIDES))
    import diagrams  # noqa: E402
    diagrams.render_all(OUT / "diagrams")
    cache: dict = {}
    problems: list[str] = []
    built = []
    for deck in decks(selected):
        text, p = resolve(deck, write=True, cache=cache)
        problems += p
        target = OUT / deck.name
        target.write_text(text, encoding="utf-8")
        built.append(target)
    if problems:
        for p in problems:
            print("ERROR", p)
        return 1
    theme = SLIDES / "theme" / "course.css"
    formats = [("html", [])] + ([("pdf", ["--pdf"])] if pdf else []) + ([("pptx", ["--pptx"])] if pptx else [])
    for target in built:
        for ext, flags in formats:
            cmd = MARP + ["--no-stdin", "--theme-set", str(theme), "--html", "--allow-local-files", *flags,
                          str(target), "-o", str(target.with_suffix(f".{ext}"))]
            subprocess.run(cmd, check=True, cwd=OUT, stdin=subprocess.DEVNULL)
            print("built", target.with_suffix(f".{ext}").relative_to(ROOT))
    shutil.copy(SLIDES / "index.html", OUT / "index.html")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that every figure reference resolves")
    ap.add_argument("--deck", action="append", help="deck file name without .md (repeatable)")
    ap.add_argument("--pdf", action="store_true")
    ap.add_argument("--pptx", action="store_true")
    args = ap.parse_args()
    try:
        return check(args.deck) if args.check else build(args.deck, args.pdf, args.pptx)
    except SlideError as exc:
        print("ERROR", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())

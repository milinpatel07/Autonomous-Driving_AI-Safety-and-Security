#!/usr/bin/env python3
"""Continuous assurance for the course's AEB safety case (safety_case/aeb_pedestrian.yaml).

    python scripts/safety_case.py --check              # integrity; exit 1 on integrity errors
    python scripts/safety_case.py --report             # update site/safety-case.md and site/safety-case.svg
    python scripts/safety_case.py --diff OLD_EVIDENCE  # exit 1 if any claim status differs from OLD_EVIDENCE

Integrity errors are structural: malformed argument, missing notebook or evidence file, invalid
evidence schema, or evidence whose producing notebook changed since it was recorded (stale).
Claim statuses are *reported*, not failures: the AEB case is intentionally "do not release".
``--diff`` compares the evidence in ``--evidence`` (default: the case's evidence directory,
e.g. freshly regenerated by executing notebooks) with a saved copy and fails when a claim
changes status, printing which claim flipped and why.
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from avsafety import assurance as A  # noqa: E402

START, END = "<!-- safety-case-status:start -->", "<!-- safety-case-status:end -->"


def evidence_register(ev: A.Evaluation, link_base: str) -> str:
    lines = ["| Evidence | Producer | Recorded (UTC) | Code hash | Dataset | Licence |", "|---|---|---|---|---|---|"]
    for eid, rec in sorted(ev.evidence.items()):
        prod = (rec.get("producer") or {})
        nb = prod.get("notebook") or ""
        ds = rec.get("dataset") or {}
        lines.append(f"| `{eid}` | [{Path(nb).stem}]({link_base}{nb}) | {rec.get('recorded_at', '')[:16].replace('T', ' ')} "
                     f"| `{(prod.get('code_hash') or 'none')[7:]}` | {ds.get('name', '')} | {ds.get('licence', '')} |")
    return "\n".join(lines)


def status_block(case: A.AssuranceCase, ev: A.Evaluation, as_of: dt.date, svg_name: str, link_base: str) -> str:
    top = ev.top
    counts = ", ".join(f"{v} {k}" for k, v in ev.counts().items())
    verdict = ("the top claim is supported" if top.status == "supported" else
               f"the top claim is **{top.status}**: the case does not support a release")
    return "\n".join([
        START,
        f"*Evaluated on {as_of.isoformat()} by `python scripts/safety_case.py --report` from "
        f"`safety_case/{Path(case.name).name}.yaml` and the committed evidence; do not edit this block by hand.*",
        "",
        f"**Result:** {verdict} (goals: {counts}; Baconian confidence {top.confidence} checks passed).",
        "",
        f"![GSN view of the AEB assurance case with evaluated statuses]({svg_name})",
        "",
        "### Claims and evidence",
        "",
        ev.to_markdown(link_base=link_base),
        "",
        "### Evidence register",
        "",
        evidence_register(ev, link_base),
        END,
    ])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--case", default=str(ROOT / "safety_case" / "aeb_pedestrian.yaml"))
    ap.add_argument("--evidence", help="evidence directory (default: the case's evidence directory)")
    ap.add_argument("--check", action="store_true", help="integrity check; exit 1 on errors")
    ap.add_argument("--report", action="store_true", help="update the site page and SVG")
    ap.add_argument("--diff", metavar="OLD_DIR", help="fail if any claim status differs from the evidence in OLD_DIR")
    ap.add_argument("--page", default=str(ROOT / "site" / "safety-case.md"))
    ap.add_argument("--svg", default=str(ROOT / "site" / "safety-case.svg"))
    ap.add_argument("--as-of", help="evaluation date YYYY-MM-DD (default today); used for evidence age rules")
    args = ap.parse_args(argv)
    if not (args.check or args.report or args.diff):
        ap.error("choose at least one of --check, --report, --diff")

    case = A.load_case(args.case, evidence_dir=args.evidence)
    as_of = dt.date.fromisoformat(args.as_of) if args.as_of else dt.date.today()
    evidence = A.load_evidence(case.evidence_dir)
    rc = 0
    summary = []

    if args.check:
        issues = case.check(evidence)
        errors = [i for i in issues if i.level == "error"]
        ev = case.evaluate(evidence, as_of=as_of)
        print(f"Case {case.name}: {len(case.nodes)} nodes, {len(evidence)} evidence files; "
              f"{len(errors)} integrity error(s), {len(issues) - len(errors)} warning(s).")
        for i in issues:
            print(" ", i)
        print(f"Top claim {case.roots()[0]}: {ev.top.status} (reported, not a failure). Goals: {ev.counts()}")
        summary.append(f"**Safety case integrity:** {len(errors)} error(s); top claim **{ev.top.status}**; goals {ev.counts()}")
        summary += [f"- {i}" for i in issues]
        rc |= 1 if errors else 0

    if args.diff:
        old_case = A.load_case(args.case, evidence_dir=args.diff)
        old = old_case.evaluate(A.load_evidence(args.diff), as_of=as_of, check_hashes=False)
        new = case.evaluate(evidence, as_of=as_of, check_hashes=False)
        flips = A.diff(old, new)
        changed_files = sorted(e for e in set(old.evidence) | set(new.evidence)
                               if (old.evidence.get(e) or {}).get("values") != (new.evidence.get(e) or {}).get("values"))
        print(f"Evidence with changed values: {', '.join(changed_files) or 'none'}")
        if flips:
            print(f"{len(flips)} claim(s) changed status:")
            summary.append(f"**Safety case diff:** {len(flips)} node(s) changed status")
            for f in flips:
                line = f"{f['node']} ({f['type']}): {f['old']} -> {f['new']}: {f['reason']}"
                print("  CLAIM FLIPPED", line)
                summary.append(f"- `{f['node']}` {f['old']} → **{f['new']}**: {f['reason']}")
                for c in f["changes"]:
                    print("      ", c)
            rc |= 1
        else:
            print("No claim changed status.")
            summary.append("**Safety case diff:** no claim changed status")

    if args.report:
        ev = case.evaluate(evidence, as_of=as_of)
        page, svg = Path(args.page), Path(args.svg)
        svg.write_text(ev.to_svg(title=f"{case.title} (evaluated {as_of.isoformat()})"), encoding="utf-8")
        base = os.path.relpath(ROOT, page.parent).replace(os.sep, "/") + "/"
        block = status_block(case, ev, as_of, os.path.relpath(svg, page.parent).replace(os.sep, "/"), base)
        text = page.read_text(encoding="utf-8") if page.exists() else f"# Safety case status\n\n{START}\n{END}\n"
        if START not in text:
            text = text.rstrip() + f"\n\n{START}\n{END}\n"
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, text, flags=re.S)
        page.write_text(text, encoding="utf-8")
        print(f"Wrote {page.relative_to(ROOT) if ROOT in page.resolve().parents else page} and {svg.name}; "
              f"top claim {ev.top.status}")

    step = os.environ.get("GITHUB_STEP_SUMMARY")
    if step and summary:
        with open(step, "a", encoding="utf-8") as fh:
            fh.write("\n".join(summary) + "\n")
    return rc


if __name__ == "__main__":
    sys.exit(main())
